// --------------------------------------------------------------------------- growth system block
function systemWidget(w) {
  if (!w) return '';
  if (w.type === 'rules') {
    return `<div class="rules" data-rules data-rule-mins="${attr(w.rules.map((r) => r.min))}">
              <div class="rules__control card"><label class="tool__label" for="rules-range"><span class="t-label-md">${esc(w.label)}</span><span class="tool__value" data-rules-value>${w.value}%</span></label><input class="range" id="rules-range" type="range" min="40" max="100" value="${w.value}" /></div>
              <ul class="rules__list" role="list">${w.rules.map((r) => `<li class="rule card"><p class="t-label-xs c-muted">${esc(r.t.toUpperCase())}</p><p class="t-p-md">${esc(r.d)}</p></li>`).join('')}</ul>
            </div>`;
  }
  if (w.type === 'funnel') {
    const max = w.steps[0].value;
    if (w.selectable) {
      return `<div class="sfunnel" data-sfunnel data-details="${attr(w.steps.map((s) => ({ label: s.label, value: s.display || String(s.value), detail: s.detail })))}">
              <ol class="sfunnel__list" role="list">${w.steps.map((s, i) => `<li><button type="button" class="sfunnel__step" aria-pressed="${i === w.selected}" style="--v: ${((s.value / max) * 100).toFixed(1)}%"><span class="t-label-xs c-muted">${esc(s.label.toUpperCase())}</span><span class="sfunnel__v">${esc(s.display || String(s.value))}</span><span class="t-p-sm c-sub">${esc(s.note)}</span><span class="sfunnel__bar" aria-hidden="true"></span></button></li>`).join('')}</ol>
              <div class="sfunnel__detail card" aria-live="polite"><p class="t-label-xs c-muted" data-sf-label></p><p class="t-label-xl" data-sf-value></p><p class="t-p-md c-sub" data-sf-detail></p></div>
            </div>`;
    }
    return `<ol class="leaks" role="list" data-leaks>${w.steps.map((s) => `<li style="--v: ${((s.value / max) * 100).toFixed(1)}%"><span class="leaks__bar"><span class="t-label-md">${esc(s.label)}</span></span>${s.note ? `<span class="leaks__note t-p-sm">${esc(s.note)}</span>` : ''}</li>`).join('')}</ol>`;
  }
  if (w.type === 'lists') {
    return `<div class="circuits">${w.lists.map((l, i) => `${i ? '<span class="circuits__bolt" aria-hidden="true">⚡</span>' : ''}<div class="circuit card" data-reveal><p class="t-label-xs c-muted">${esc(l.k.toUpperCase())}</p><p class="t-label-xl">${esc(l.t)}</p><ul class="dot-list" role="list">${l.items.map((x) => `<li><span class="dot" aria-hidden="true"></span>${esc(x)}</li>`).join('')}</ul></div>`).join('')}</div>`;
  }
  if (w.type === 'stagelist') {
    return `<ol class="stagelist" role="list" data-reveal-stagger="0.05">${STAGES.map((st, i) => `<li class="stagelist__item${i === 6 ? ' is-lean' : ''}" data-reveal><span class="t-label-xs c-muted">${pad(i + 1)}</span><span class="t-label-md">${st}</span><span class="t-p-sm c-sub">${esc(w.lines[i])}</span></li>`).join('')}</ol>`;
  }
  return '';
}

