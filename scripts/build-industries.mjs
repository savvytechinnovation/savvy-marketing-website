// --------------------------------------------------------------------------- shared blocks
function calendarChart(cal, id) {
  const totals = MONTHS.map((_, m) => cal.series.reduce((s, x) => s + x.values[m], 0));
  const max = Math.max(...totals) * 1.08;
  const W = 1200;
  const H = 300;
  const cw = W / 12;
  const bw = cw * 0.56;
  const cols = MONTHS.map((mo, m) => {
    let y = H;
    const rects = cal.series
      .map((s, k) => {
        const h = (s.values[m] / max) * H;
        y -= h;
        return h > 0 ? `<rect class="cal__bar cal__bar--${k}" data-series="${k}" x="${(m * cw + (cw - bw) / 2).toFixed(1)}" y="${y.toFixed(1)}" width="${bw.toFixed(1)}" height="${h.toFixed(1)}" rx="6" />` : '';
      })
      .join('');
    return `<g class="cal__col" data-month="${m}">${rects}<rect class="cal__hit" x="${m * cw}" y="0" width="${cw}" height="${H}" /></g>`;
  });
  const marks = cal.marks
    ? Object.entries(cal.marks)
        .map(([m, label]) => `<span class="cal__mark" style="--m: ${m}">${esc(label)}</span>`)
        .join('')
    : '';
  return `<div class="cal" data-calendar data-values="${attr(cal.series.map((s) => s.values))}" data-names="${attr(cal.series.map((s) => s.name))}" data-reveal>
            <div class="cal__legend" role="group" aria-label="Show a demand type">
              ${cal.series.map((s, k) => `<button type="button" class="cal__key" data-series="${k}" aria-pressed="false"><span class="cal__swatch cal__swatch--${k}" aria-hidden="true"></span>${esc(s.name)}</button>`).join('\n              ')}
            </div>
            <div class="cal__plot">
              ${marks ? `<div class="cal__marks" aria-hidden="true">${marks}</div>` : ''}
              <svg class="cal__svg" viewBox="0 0 ${W} ${H}" preserveAspectRatio="none" aria-hidden="true" focusable="false">${cols.join('')}</svg>
              <div class="cal__tip" role="status" aria-live="polite" data-cal-tip hidden></div>
            </div>
            <div class="cal__months" role="group" aria-label="Months">
              ${MONTHS.map((mo, m) => `<button type="button" class="cal__month" data-month="${m}" aria-label="${mo}: ${cal.series.map((s) => `${esc(s.name)} ${s.values[m]}`).join(', ')}">${mo}</button>`).join('')}
            </div>
            <div class="sr-only"><table id="${id}-table">
              <caption>Relative demand by month (0–100, illustrative)</caption>
              <thead><tr><th scope="col">Month</th>${cal.series.map((s) => `<th scope="col">${esc(s.name)}</th>`).join('')}</tr></thead>
              <tbody>${MONTHS.map((mo, m) => `<tr><th scope="row">${mo}</th>${cal.series.map((s) => `<td>${s.values[m]}</td>`).join('')}</tr>`).join('')}</tbody>
            </table></div>
          </div>`;
}

