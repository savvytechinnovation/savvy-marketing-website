function postsBlock() {
  const list = {
    '@context': 'https://schema.org',
    '@type': 'ItemList',
    itemListElement: posts.map((p, i) => ({ '@type': 'ListItem', position: i + 1, url: abs(url(p)), name: p.title })),
  };
  return `${posts.map((p) => card(p)).join('\n')}\n${jsonLd(list)}`;
}

function replaceBlock(html, name, content) {
  const re = new RegExp(`([ \\t]*)<!-- ${name}:start -->[\\s\\S]*?<!-- ${name}:end -->`);
  if (!re.test(html)) throw new Error(`resources/index.html is missing the <!-- ${name}:start --> / <!-- ${name}:end --> markers`);
  return html.replace(re, (_, pad) => `${pad}<!-- ${name}:start -->\n${indent(content, pad.length)}\n${pad}<!-- ${name}:end -->`);
}

