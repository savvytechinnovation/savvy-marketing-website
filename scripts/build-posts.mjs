#!/usr/bin/env node
// Static generator for the Resources section.
//
//   node scripts/build-posts.mjs            (optionally: SITE_URL=https://www.example.com node scripts/build-posts.mjs)
//
// Reads src/content/posts.js and
//   1. writes resources/<slug>/index.html for every post (article template, Figma "Blog Page"),
//   2. regenerates the marked blocks inside resources/index.html (Figma "Resources"):
//        <!-- types:start -->      … <!-- types:end -->       format tabs with counts
//        <!-- featured:start -->   … <!-- featured:end -->    featured resource
//        <!-- posts:start -->      … <!-- posts:end -->       every resource card (JS only filters/reorders them)
//        <!-- newsletter:start --> … <!-- newsletter:end -->  newsletter + soft CTA section
//   3. removes article folders it generated earlier for posts that no longer exist.
// No dependencies beyond Node 18+. The generated HTML is committed, so the site builds without running this.
// SITE_URL (no trailing slash) makes canonical/og/JSON-LD URLs absolute; without it they stay root-relative.

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { AUTHORS, INDUSTRIES, STAGES, TYPES, posts as allPosts } from '../src/content/posts.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SITE_URL = (process.env.SITE_URL || '').replace(/\/$/, '');
const GENERATED = '<!-- generated by scripts/build-posts.mjs from src/content/posts.js: edit the content, not this file -->';
const SITE_NAME = 'Savvy Marketing Partners';
const COMPANY = 'Savvy Post Marketing';

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------
const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
const slugify = (s) =>
  String(s)
    .toLowerCase()
    .replace(/&[a-z]+;/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
const stripTags = (html) => String(html).replace(/<[^>]+>/g, '');
const decode = (s) =>
  String(s)
    .replace(/&rsquo;|&lsquo;/g, "'")
    .replace(/&ldquo;|&rdquo;/g, '"')
    .replace(/&ndash;/g, '–')
    .replace(/&mdash;/g, '—')
    .replace(/&times;/g, '×')
    .replace(/&amp;/g, '&');
const plain = (html) => decode(stripTags(html));
const abs = (path) => `${SITE_URL}${path}`;
const url = (post) => `/resources/${post.slug}/`;
const fmtDate = (iso) => new Date(`${iso}T12:00:00Z`).toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric', timeZone: 'UTC' });
const fmtDateLong = (iso) => new Date(`${iso}T12:00:00Z`).toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric', timeZone: 'UTC' });
const plural = { Guide: 'Guides', Breakdown: 'Breakdowns', Findings: 'Findings', Checklist: 'Checklists' };
const readLabel = { Guide: 'Read the guide', Breakdown: 'Read the breakdown', Findings: 'Read the findings', Checklist: 'Open the checklist' };
const icon = (name, w = 16, h = 16, cls = '') => `<img${cls ? ` class="${cls}"` : ''} src="/ds/icons/${name}.svg" alt="" width="${w}" height="${h}" />`;
const btnIcon = `<span class="btn__icon">${icon('arrow-up-right', 20, 20)}</span>`;
const jsonLd = (data) => `<script type="application/ld+json">${JSON.stringify(data).replace(/</g, '\\u003c')}</script>`;
const indent = (html, n) => html.replace(/^(?=.)/gm, ' '.repeat(n));

const posts = [...allPosts].sort((a, b) => b.date.localeCompare(a.date));
// Issue numbers: chronological (oldest = No. 01), shown on covers and cards
const chron = [...posts].reverse();
const issueNo = (post) => String(chron.indexOf(post) + 1).padStart(2, '0');
const TOTAL = String(posts.length).padStart(2, '0');

function validate() {
  const slugs = new Set();
  for (const post of posts) {
    const where = `post "${post.slug}"`;
    if (!/^[a-z0-9-]+$/.test(post.slug)) throw new Error(`${where}: invalid slug`);
    if (slugs.has(post.slug)) throw new Error(`${where}: duplicate slug`);
    slugs.add(post.slug);
    if (!TYPES.includes(post.type)) throw new Error(`${where}: unknown type ${post.type}`);
    if (post.industry !== 'All industries' && !INDUSTRIES.includes(post.industry)) throw new Error(`${where}: unknown industry ${post.industry}`);
    for (const s of post.stages) if (!STAGES.includes(s)) throw new Error(`${where}: unknown stage ${s}`);
    if (!AUTHORS[post.author]) throw new Error(`${where}: unknown author ${post.author}`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(post.date)) throw new Error(`${where}: date must be YYYY-MM-DD`);
  }
}

const wordCount = (post) =>
  [post.dek, ...post.takeaways, ...post.body.map((b) => [b.text, b.html, b.cite, b.label, b.caption, ...(b.items || []), ...(b.head || []), ...(b.rows || []).flat()].join(' '))]
    .map(plain)
    .join(' ')
    .split(/\s+/)
    .filter(Boolean).length;

