// ---------------------------------------------------------------------------
// Run
// ---------------------------------------------------------------------------
validate();

const outDir = join(root, 'resources');
mkdirSync(outDir, { recursive: true });
const report = [];
for (const post of posts) {
  const dir = join(outDir, post.slug);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'index.html'), articlePage(post));
  report.push(`  /resources/${post.slug}/  (${wordCount(post)} words, ${post.minutes} min)`);
}

// Remove folders this script generated for posts that were deleted or renamed.
for (const entry of readdirSync(outDir, { withFileTypes: true })) {
  if (!entry.isDirectory() || posts.some((p) => p.slug === entry.name)) continue;
  const file = join(outDir, entry.name, 'index.html');
  if (existsSync(file) && readFileSync(file, 'utf8').includes(GENERATED)) {
    rmSync(join(outDir, entry.name), { recursive: true });
    report.push(`  removed stale /resources/${entry.name}/`);
  }
}

const hubFile = join(outDir, 'index.html');
if (!existsSync(hubFile)) throw new Error('resources/index.html not found (it holds the hub layout and the marker blocks).');
let hub = readFileSync(hubFile, 'utf8');
hub = replaceBlock(hub, 'types', typesBlock());
hub = replaceBlock(hub, 'hero-meta', heroMetaBlock());
hub = replaceBlock(hub, 'marquee', marqueeBlock());
hub = replaceBlock(hub, 'rail', railBlock());
hub = replaceBlock(hub, 'featured', featuredBlock());
hub = replaceBlock(hub, 'posts', postsBlock());
hub = replaceBlock(hub, 'newsletter', softCta({ key: 'hub', path: '/resources/' }));
hub = hub.replace(/data-total="\d+"/g, `data-total="${posts.length}"`);
writeFileSync(hubFile, hub);

console.log(`Resources: generated ${posts.length} articles and updated resources/index.html\n${report.join('\n')}`);
