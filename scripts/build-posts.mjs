const eyebrow = (post) => `${post.type} · ${post.industry}`;

/** Resource card (Figma "Resource Card" 5499:174). Data attributes drive client-side filtering. */
function card(post, { headingLevel = 3, filterable = true } = {}) {
  const industry = post.industry === 'All industries' ? 'all' : slugify(post.industry);
  const search = plain([post.title, post.excerpt, post.type, post.industry, ...post.stages].join(' ')).toLowerCase();
  const data = filterable
    ? ` data-type="${slugify(post.type)}" data-industry="${industry}" data-audience="${post.audience.map(slugify).join(' ')}" data-stages="${post.stages.map(slugify).join(' ')}" data-date="${post.date}" data-minutes="${post.minutes}" data-slug="${post.slug}" data-search="${esc(search)}"`
    : '';
  return `<li class="rcard-item"${data}>
  <article class="rcard">
    <a class="rcard__link" href="${url(post)}" data-cursor="view">
      <span class="ph rcard__media" aria-hidden="true" data-cover="${post.slug}"><span class="rcard__no">No. ${issueNo(post)}</span><span class="rcard__glare"></span></span>
      <span class="rcard__body">
        <span class="rcard__eyebrow">${esc(eyebrow(post))}</span>
        <h${headingLevel} class="rcard__title">${esc(post.title)}</h${headingLevel}>
        <span class="rcard__meta">${post.minutes} min read</span>
      </span>
    </a>
  </article>
</li>`;
}

